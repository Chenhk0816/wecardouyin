const assert=require('node:assert/strict');
const fs=require('node:fs');
assert.ok(fs.existsSync('prototype/douyin-model.js'),'new workflow business model exists');
const M=require('../prototype/douyin-model.js');
const s=M.createState();
assert.equal(M.accounts(s).length,0,'disconnected state has no authorized publishing accounts');
M.demoAuthorize(s,'douyin','a-hq',['publish'],['a-river']);
M.demoAuthorize(s,'laike','a-merchant',['goods','sales','verify'],['a-river']);
assert.equal(M.accounts(s).length,1);
assert.equal(M.accounts(s,'b-hill').length,0,'account grant cannot leak to another tenant store');
s.brief=M.prefill('滨江店周末会员活动，做30秒竖屏，专业可信，不要出现明火和夸大宣传');
assert.equal(s.brief.duration,'30'); assert.match(s.brief.avoid,/明火/);
s.asset={id:'sample-v1',kind:'demo',name:'示例成片',confirmed:true};
s.target={account:'a-hq',shop:'a-river',product:'a-gift',title:'周末活动'};
assert.equal(M.validatePublish(s),'');
M.previewPublish(s);s.ack=true;assert.equal(M.savePublish(s).ok,true);
assert.equal(M.savePublish(s).duplicate,true,'double click does not duplicate');
s.target.title='新标题';assert.equal(M.savePublish(s).ok,false,'changed content requires new preview');
M.previewPublish(s);s.ack=true;M.revoke(s,'douyin','a-hq');assert.equal(M.savePublish(s).ok,false,'revocation invalidates confirmation');
M.demoAuthorize(s,'douyin','a-hq',['publish'],['a-river']);
s.grants.find(g=>g.id==='a-hq').expires=0;assert.match(M.validatePublish(s),/授权/,'expired grant rejected');
M.demoAuthorize(s,'douyin','a-hq',['publish'],['a-river']);s.target.product='b-gift';assert.match(M.validatePublish(s),/商品/,'foreign product rejected');
s.target.product='a-old';assert.match(M.validatePublish(s),/商品/,'offline product rejected');
s.target.product='a-gift';assert.match(M.validatePublish(s,true),/接入|挂载/,'real publishing blocked without adapters');
M.changeTenant(s,'b');assert.equal(M.accounts(s).length,0);assert.equal(s.preview,null);assert.equal(s.asset,null);assert.equal(s.brief,null);
const r=M.dailyReport(s,'b-hill','2026-10-23',false);assert.equal(r.metrics[0].value,null);assert.equal(r.reviews,null,'unknown is not zero');
assert.equal(M.validLiveUrl('https://evil.com/live.douyin.com/123'),false);
assert.equal(M.validLiveUrl('https://live.douyin.com/123'),true);
assert.equal(M.validLiveUrl('javascript:alert(1)'),false);
assert.equal(M.liveAssessment(false).level,'需补充核验');
assert.equal(M.liveAssessment(true).dimensions[3].status,'需核验','sample frames cannot establish paid traffic');
console.log('PASS: scope isolation, expiration/revocation, brief prefill, publication confirmation/idempotency, unavailable data, live evidence');
